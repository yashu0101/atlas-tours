import fs from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import {
  catalogKeys,
  en,
  getMessages,
  getT,
  hi,
  interpolate,
  missingKeys,
  translate,
  type MessageKey,
} from "@/lib/i18n";

const DOC_PATH = path.resolve(__dirname, "../../docs/hindi-strings-needed.md");

/** Markdown table of every English string that has no Hindi yet (docs/hindi-strings-needed.md). */
function hindiTodoMarkdown(): string {
  const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
  const missing = missingKeys("hi");
  const rows = missing.map((k) => `| \`${k}\` | ${cell(translate("en", k))} | |`);
  return [
    "# Hindi strings needed (G-08)",
    "",
    "The public site's UI text now comes from a message catalog (`src/lib/i18n/en.ts`).",
    "Every row below is shown in **English** when a visitor switches to Hindi, because no Hindi text has been supplied yet.",
    "Please fill in the **Hindi** column; a developer copies each entry into `src/lib/i18n/hi.ts` under the same key.",
    "",
    "Notes for translators:",
    "",
    "- Keep `{placeholders}` exactly as written (e.g. `{name}`, `{year}`) — they are replaced with real values.",
    "- Text ending in `Aria` is read aloud by screen readers only; it is not visible on the page.",
    "- Package, blog, FAQ and offer content is managed in the admin panel and is not part of this list.",
    "",
    `Untranslated strings: **${missing.length}** of ${catalogKeys(en).length}.`,
    "",
    "_Generated by `tests/unit/i18n.test.ts` — regenerate with `UPDATE_HINDI_DOC=1 npx vitest run tests/unit/i18n.test.ts`._",
    "",
    "| Key | English | Hindi |",
    "|---|---|---|",
    ...rows,
    "",
  ].join("\n");
}

describe("i18n catalog", () => {
  it("returns English for lang=en", () => {
    expect(translate("en", "header.nav.home")).toBe("Home");
    expect(translate("en", "hero.discover")).toBe("Discover");
  });

  it("falls back to English when a Hindi string is missing", () => {
    expect(missingKeys("hi")).toContain("hero.welcome");
    expect(translate("hi", "hero.welcome")).toBe("Welcome to Atlas Tours");
    expect(getMessages("hi").hero.welcome).toBe("Welcome to Atlas Tours");
  });

  it("falls back to the key for an unknown key at runtime", () => {
    expect(translate("en", "nope.missing" as MessageKey)).toBe("nope.missing");
  });

  it("rejects unknown keys at compile time", () => {
    // @ts-expect-error — not a catalog key
    expect(translate("en", "header.nav.nope")).toBe("header.nav.nope");
  });

  it("interpolates {placeholders}", () => {
    expect(translate("en", "footer.copyright", { year: 2026 })).toBe("© 2026 Atlas Tours. All rights reserved.");
    expect(translate("en", "reviews.slideAria", { current: 2, total: 3 })).toBe("2 of 3");
    expect(translate("hi", "packages.enquiryMessage", { name: "Kashi Darshan" })).toBe(
      "Hi! I'm interested in the Kashi Darshan package."
    );
    // Unknown placeholders are left untouched; missing vars don't throw.
    expect(interpolate("{a} and {b}", { a: "x" })).toBe("x and {b}");
    expect(interpolate("no vars")).toBe("no vars");
  });

  it("getT binds a language", () => {
    const t = getT("en");
    expect(t("common.percentOff", { percent: 15 })).toBe("15% OFF");
  });

  it("preserves the existing Hindi header labels exactly", () => {
    expect(translate("hi", "header.nav.home")).toBe("होम");
    expect(translate("hi", "header.nav.about")).toBe("हमारे बारे में");
    expect(translate("hi", "header.nav.packages")).toBe("पैकेज");
    expect(translate("hi", "header.nav.gallery")).toBe("गैलरी");
    expect(translate("hi", "header.nav.blog")).toBe("ब्लॉग");
    expect(translate("hi", "header.nav.faq")).toBe("सवाल");
    expect(translate("hi", "header.nav.contact")).toBe("संपर्क");
    expect(translate("hi", "header.callNow")).toBe("कॉल करें");
    // The language switch names the language you switch to.
    expect(translate("en", "header.langToggle")).toBe("हिंदी");
    expect(translate("hi", "header.langToggle")).toBe("EN");
  });

  it("every Hindi key exists in English", () => {
    const enKeys = new Set(catalogKeys(en));
    const extra = catalogKeys(hi).filter((k) => !enKeys.has(k));
    expect(extra).toEqual([]);
  });

  it("has no empty strings", () => {
    for (const k of catalogKeys(en)) expect(translate("en", k as MessageKey), k).not.toBe("");
    for (const k of catalogKeys(hi)) expect(translate("hi", k as MessageKey).trim(), k).not.toBe("");
  });

  it("docs/hindi-strings-needed.md lists every untranslated string", () => {
    const missing = missingKeys("hi");
    console.info(`[i18n] ${missing.length} of ${catalogKeys(en).length} English keys have no Hindi translation.`);
    const expected = hindiTodoMarkdown();
    if (process.env.UPDATE_HINDI_DOC) {
      fs.mkdirSync(path.dirname(DOC_PATH), { recursive: true });
      fs.writeFileSync(DOC_PATH, expected);
    }
    const actual = fs.readFileSync(DOC_PATH, "utf8").replace(/\r\n/g, "\n");
    expect(actual, "docs/hindi-strings-needed.md is stale — rerun with UPDATE_HINDI_DOC=1").toBe(expected);
  });
});
